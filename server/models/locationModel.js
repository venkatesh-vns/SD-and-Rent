const { pool } = require('../config/db');
const { listOf, idsOf } = require('../utils/filters');

// One definition per level of the Location Master hierarchy.
// `parents` lists the parent id columns a record of this level carries.
const LEVELS = {
  1: { table: 'location_l1', id: 'l1_id', code: 'l1_code', name: 'l1_name', parents: [] },
  2: { table: 'location_l2', id: 'l2_id', code: 'l2_code', name: 'l2_name', parents: ['l1_id'] },
  3: { table: 'location_l3', id: 'l3_id', code: 'l3_code', name: 'l3_name', parents: ['l1_id', 'l2_id'] },
};

// Selects a level's rows with their parents' codes and names alongside
function baseSelect(level) {
  if (level === 1) return 'SELECT t.* FROM location_l1 t';
  if (level === 2) {
    return `SELECT t.*, p1.l1_code, p1.l1_name, p1.status AS l1_status
            FROM location_l2 t JOIN location_l1 p1 ON p1.l1_id = t.l1_id`;
  }
  return `SELECT t.*, p1.l1_code, p1.l1_name, p1.status AS l1_status,
                 p2.l2_code, p2.l2_name, p2.status AS l2_status
          FROM location_l3 t
          JOIN location_l1 p1 ON p1.l1_id = t.l1_id
          JOIN location_l2 p2 ON p2.l2_id = t.l2_id`;
}

// Filters: search (code or name); status, l1Id, l2Id accept one or more values
async function getAll(level, { search, status, l1Id, l2Id } = {}) {
  const def = LEVELS[level];
  const where = [];
  const params = [];
  if (search) {
    params.push(`%${search}%`);
    where.push(`(t.${def.code} ILIKE $${params.length} OR t.${def.name} ILIKE $${params.length})`);
  }
  if (listOf(status).length) {
    params.push(listOf(status));
    where.push(`t.status = ANY($${params.length})`);
  }
  if (idsOf(l1Id).length && def.parents.includes('l1_id')) {
    params.push(idsOf(l1Id));
    where.push(`t.l1_id = ANY($${params.length}::int[])`);
  }
  if (idsOf(l2Id).length && def.parents.includes('l2_id')) {
    params.push(idsOf(l2Id));
    where.push(`t.l2_id = ANY($${params.length}::int[])`);
  }
  const order = level === 1 ? 't.l1_name' : level === 2 ? 'p1.l1_name, t.l2_name' : 'p1.l1_name, p2.l2_name, t.l3_name';
  const result = await pool.query(
    `${baseSelect(level)} ${where.length ? `WHERE ${where.join(' AND ')}` : ''} ORDER BY ${order}`,
    params
  );
  return result.rows;
}

async function findById(level, id, db = pool) {
  const result = await db.query(`${baseSelect(level)} WHERE t.${LEVELS[level].id} = $1`, [id]);
  return result.rows[0];
}

// Case-insensitive lookup of a record by name within its parent
// (parentId = l1_id for level 2, l2_id for level 3; ignored for level 1)
async function findByName(level, name, parentId = null, excludeId = null) {
  const def = LEVELS[level];
  const params = [name];
  let query = `SELECT * FROM ${def.table} WHERE LOWER(${def.name}) = LOWER($1)`;
  if (level > 1) {
    params.push(parentId);
    query += ` AND ${def.parents[def.parents.length - 1]} = $${params.length}`;
  }
  if (excludeId) {
    params.push(excludeId);
    query += ` AND ${def.id} <> $${params.length}`;
  }
  const result = await pool.query(query, params);
  return result.rows[0];
}

// Case-insensitive lookup by code, or by name within the parent (used by
// uploads that reference locations). parentId as in findByName.
async function findByCodeOrName(level, value, parentId = null) {
  const def = LEVELS[level];
  const byCode = await pool.query(`SELECT * FROM ${def.table} WHERE UPPER(${def.code}) = UPPER($1)`, [value]);
  if (byCode.rows[0]) return byCode.rows[0];
  return findByName(level, value, parentId);
}

// data: { name, status, l1Id?, l2Id? }; the code is generated by the database
async function create(level, data, createdBy, { uploaded = false } = {}, db = pool) {
  const def = LEVELS[level];
  const columns = [def.name, 'status', ...def.parents, 'created_by', 'uploaded_by', 'uploaded_date'];
  const values = [
    data.name, data.status || 'Active',
    ...def.parents.map((p) => (p === 'l1_id' ? data.l1Id : data.l2Id)),
    createdBy, uploaded ? createdBy : null, uploaded ? new Date() : null,
  ];
  const result = await db.query(
    `INSERT INTO ${def.table} (${columns.join(', ')})
     VALUES (${values.map((_, i) => `$${i + 1}`).join(', ')})
     RETURNING ${def.id}`,
    values
  );
  return findById(level, result.rows[0][def.id], db);
}

// Name, status and parent(s) can change; the code cannot.
// Changing a Level 2's Level 1 carries its Level 3 records with it (ON UPDATE CASCADE).
async function update(level, id, data, modifiedBy, db = pool) {
  const def = LEVELS[level];
  const sets = [`${def.name} = $1`, 'status = $2'];
  const values = [data.name, data.status];
  def.parents.forEach((p) => {
    values.push(p === 'l1_id' ? data.l1Id : data.l2Id);
    sets.push(`${p} = $${values.length}`);
  });
  values.push(modifiedBy, id);
  await db.query(
    `UPDATE ${def.table} SET ${sets.join(', ')}, modified_by = $${values.length - 1}, modified_date = NOW()
     WHERE ${def.id} = $${values.length}`,
    values
  );
  return findById(level, id, db);
}

async function remove(level, id, db = pool) {
  const def = LEVELS[level];
  await db.query(`DELETE FROM ${def.table} WHERE ${def.id} = $1`, [id]);
}

// Number of child records under a Level 1 or Level 2
async function countChildren(level, id) {
  if (level === 3) return 0;
  const child = LEVELS[level + 1];
  const result = await pool.query(
    `SELECT COUNT(*)::int AS n FROM ${child.table} WHERE ${LEVELS[level].id} = $1`,
    [id]
  );
  return result.rows[0].n;
}

module.exports = { LEVELS, getAll, findById, findByName, findByCodeOrName, create, update, remove, countChildren };
