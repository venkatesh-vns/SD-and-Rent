const { pool } = require('../config/db');

// Optional filters: search (code or name, partial match), status
async function getAll({ search, status } = {}) {
  const where = [];
  const params = [];
  if (search) {
    params.push(`%${search}%`);
    where.push(`(cost_center_code ILIKE $${params.length} OR cost_center_name ILIKE $${params.length})`);
  }
  if (status) {
    params.push(status);
    where.push(`status = $${params.length}`);
  }
  const result = await pool.query(
    `SELECT * FROM cost_centers
     ${where.length ? `WHERE ${where.join(' AND ')}` : ''}
     ORDER BY cost_center_id DESC`,
    params
  );
  return result.rows;
}

// Case-insensitive lookup by code or name (used by uploads)
async function findByCodeOrName(value) {
  const result = await pool.query(
    'SELECT * FROM cost_centers WHERE UPPER(cost_center_code) = UPPER($1) OR LOWER(cost_center_name) = LOWER($1) ORDER BY (UPPER(cost_center_code) = UPPER($1)) DESC LIMIT 1',
    [value]
  );
  return result.rows[0];
}

async function findById(costCenterId, db = pool) {
  const result = await db.query('SELECT * FROM cost_centers WHERE cost_center_id=$1', [costCenterId]);
  return result.rows[0];
}

// cost_center_code is generated by the database (CC0001, CC0002, ...)
async function create({ name, status, createdBy, uploaded = false }, db = pool) {
  const result = await db.query(
    `INSERT INTO cost_centers (cost_center_name, status, created_by, uploaded_by, uploaded_date)
     VALUES ($1, $2, $3, $4, $5)
     RETURNING *`,
    [name, status || 'Active', createdBy || 'System', uploaded ? createdBy : null, uploaded ? new Date() : null]
  );
  return result.rows[0];
}

// The code is fixed once generated; only name and status can change
async function update(costCenterId, { name, status, modifiedBy }, db = pool) {
  const result = await db.query(
    `UPDATE cost_centers SET cost_center_name=$1, status=$2,
     modified_by=$3, modified_date=NOW()
     WHERE cost_center_id=$4
     RETURNING *`,
    [name, status, modifiedBy || 'System', costCenterId]
  );
  return result.rows[0];
}

async function remove(costCenterId, db = pool) {
  await db.query('DELETE FROM cost_centers WHERE cost_center_id=$1', [costCenterId]);
}

// Case-insensitive duplicate check on name
async function existsByName(name, excludeId = null) {
  let query = 'SELECT cost_center_id FROM cost_centers WHERE LOWER(cost_center_name)=LOWER($1)';
  const params = [name];
  if (excludeId) {
    query += ' AND cost_center_id <> $2';
    params.push(excludeId);
  }
  const result = await pool.query(query, params);
  return result.rows.length > 0;
}

module.exports = { getAll, findById, findByCodeOrName, create, update, remove, existsByName };
